def t_t1_systems() -> str:
    t = "tab_t1_systems"
    rows, comments = [], []
    for key, lab in T1_SYS:
        b = f"tables.07_t1_systems.systems.{key}"
        v1 = get(b)
        SOURCES.setdefault(t, {})[b + " (v1, comment only)"] = {"flag": v1["flag_macro_f1"]["value"], "collapsed": v1["collapsed_macro_f1"]["value"]}
        comments.append(f"% v1 gold: {lab}: 3-way {v1['flag_macro_f1']['value']:.3f}, collapsed {v1['collapsed_macro_f1']['value']:.3f}, "
                        f"different F1 {v1['judgement_f1_per_label']['different']:.3f}, coverage {v1['coverage']['value']:.3f} (n {v1['n_items']})")
        rows.append([lab, ph(f"{key}-n"), ph(f"{key}-3way"), ph(f"{key}-collapsed"), ph(f"{key}-diffF1"), ph(f"{key}-coverage")])
    rows.append(["Structured comparator", ph("cmp-n"), "--", "--", ph("cmp-diffF1"), ph("cmp-coverage")])
    return "\n".join(comments) + "\n" + tex_table(
        "tab:t1", "T1 systems on gold v2 (3-way flag Macro-F1, collapsed absent-vs-present Macro-F1, \\textit{different} F1, coverage).",
        "lccccc", ["System", "$n$", "3-way F1", "Collapsed F1", "\\textit{different} F1", "Coverage"], rows,
        note="CIs: 2{,}000 item resamples. Collapsed F1 is the fair comparison with P2-002, which cannot express shared vs class-specific.",
        wide=True)


def t_t2() -> str:
    t = "tab_t2"
    sets = ["t2_xclass_t1", "t2_xclass_p2002", "t2_supp_p2003"]
    rows = []
    for s_key, lab in [("bm25", "BM25"), ("dense", "Dense (bge-base)"), ("hybrid_rrf", "Hybrid (RRF)"),
                       ("hybrid_minus_source_class", "Hybrid $-$ source class"), ("class_aware", "Class-aware hybrid")]:
        rows.append([lab] + [ci(t, f"tables.06_t2_retrieval.p3001.{s}.systems.{s_key}.ndcg") for s in sets])
    n = [num(t, f"tables.06_t2_retrieval.p3001.{s}.n_scored", "{}") for s in sets]
    return tex_table("tab:t2", "T2 counterpart retrieval, nDCG@10 [95\\% CI].", "lccc",
                     ["System", f"xclass\\_t1 ($n$={n[0]})", f"xclass\\_p2002 ($n$={n[1]})", f"supp\\_p2003 ($n$={n[2]})"], rows,
                     note="Each relevance set favours one retriever (first two: dense; third: BM25). The class-aware gain is partly by construction.",
                     wide=True)


