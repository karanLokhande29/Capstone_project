def t_reliability() -> str:
    t = "tab_reliability"
    irr = "tables.05_t1_benchmark.irr.fleiss"

    def k(path):
        b = get(path)
        SOURCES.setdefault(t, {})[path] = {"kappa": b["kappa"], "ci95": b["bootstrap"]["ci95"], "n_items": b["n_items"]}
        return f"{b['kappa']:.3f} [{b['bootstrap']['ci95'][0]:.3f}, {b['bootstrap']['ci95'][1]:.3f}]"

    rows = [["P: new first-pass (93)", ph("P-class-k"), ph("P-flag-k"), ph("P-notobl-k")],
            ["P-kept (79)", ph("Pk-class-k"), ph("Pk-flag-k"), ph("Pk-notobl-k")],
            ["S: P + separate 30", ph("S-class-k"), ph("S-flag-k"), ph("S-notobl-k")],
            ["Separate 30-item set (as published)", k(f"{irr}.per_class_judgement"), k(f"{irr}.differential_flag"), k(f"{irr}.not_obligation")],
            ["B: seen before, not independent (30)", ph("B-class-k"), ph("B-flag-k"), ph("B-notobl-k")],
            ["15-h retest, rater\\_2 / rater\\_3 (19 each)", ph("RT-class-k"), ph("RT-flag-k"), ph("RT-notobl-k")]]
    return tex_table("tab:reliability", "T1 reliability: Fleiss' $\\kappa$ (retest: Cohen's $\\kappa$), 95\\% bootstrap CI over items.",
                     "lccc", ["Set", "Class judgement", "Flag", "Not-obligation"], rows,
                     note="Primary = P. Flag and class statistics use items all raters labelled as obligations. B is never pooled. "
                          "Retest is supplementary (recall may inflate agreement).", wide=True)


