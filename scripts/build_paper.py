def build_main() -> None:
    p = PAPER / "main.tex"
    if p.exists():
        return  # never overwrite the authors' file
    secs = []
    for i, (key, title) in enumerate(SECTIONS, start=1):
        fl = "\n".join(FLOATS.get(key, []))
        secs.append(f"\\section{{{title}}}\\label{{sec:{key}}}\n% CONTENT BRIEF: briefs/{i:02d}_{key}.md\n"
                    f"\\placeholder{{SECTION TEXT ({title}): authors write from briefs/{i:02d}_{key}.md}}\n{fl}\n")
    write("main.tex", MAIN.replace("%%SECTIONS%%", "\n".join(secs)))


