#!/usr/bin/env python3
"""AISIGH-SD 2026 paper skeleton (IEEEtran, Overleaf-compilable, no shell-escape) and content briefs. Writes NO paper prose.

    python3 scripts/build_paper.py          # regenerate tables, figures, refs, briefs, space budget (main.tex only if absent)
    python3 scripts/check_paper.py          # build check: fails while any \\placeholder{} remains

**Output (paper/aisigh/):**
- `tables/*.tex`: every number comes from reports/results_v1.json, with its key recorded in tables/sources.json.
  T1 v2 numbers are `\\placeholder{}` (the v1 value is kept in a comment).
- `figures/`: the draft figures.
- (refs_verified.bib is maintained by hand from the verified references; this script does not write a bibliography.)
- `briefs/*.md`: for each section, the claims, the numbers with their source keys, the disclosures and a word budget.
- `space_budget.md`.

The authors write every paragraph.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper/aisigh"
R = json.loads((ROOT / "reports/results_v1.json").read_text())
SOURCES: dict[str, dict[str, object]] = {}


def get(key: str):
    v = R
    for k in key.split("."):
        v = v[int(k)] if isinstance(v, list) else v[k]
    return v


def num(table: str, key: str, fmt: str = "{:.3f}") -> str:
    v = get(key)
    SOURCES.setdefault(table, {})[key] = v
    return fmt.format(v)


def ci(table: str, key: str, lo="ci_low", hi="ci_high", point="mean", signed=False) -> str:
    base = get(key)
    p, a, b = base[point], base[lo], base[hi]
    SOURCES.setdefault(table, {})[key] = {point: p, lo: a, hi: b}
    f = (lambda x: f"{x:+.3f}") if signed else (lambda x: f"{x:.3f}")
    return f"{f(p)} [{f(a)}, {f(b)}]"


def ph(name: str) -> str:
    return f"\\placeholder{{{name}}}"


def write(rel: str, text: str) -> None:
    p = PAPER / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")


def tex_table(label: str, caption: str, cols: str, header: list[str], rows: list[list[str]], note: str = "",
              wide: bool = False) -> str:
    env = "table*" if wide else "table"
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    return (f"% GENERATED by scripts/build_paper.py from reports/results_v1.json (keys: tables/sources.json). Do not edit numbers by hand.\n"
            f"\\begin{{{env}}}[t]\n\\centering\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\small\n"
            f"\\begin{{tabular}}{{{cols}}}\n\\toprule\n{' & '.join(header)} \\\\\n\\midrule\n{body}\n\\bottomrule\n\\end{{tabular}}\n"
            + (f"\\par\\smallskip{{\\footnotesize {note}}}\n" if note else "") + f"\\end{{{env}}}\n")


