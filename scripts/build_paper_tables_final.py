#!/usr/bin/env python3
"""Final paper tables (FINAL-MASTER-AND-PAPER Part C), generated from reports/results_v2.json — never hand-typed.

    python3 scripts/build_paper_tables_final.py   -> paper/aisigh/tables/*.tex + tables/sources_final.json

Scope:
- gold = t1_validated_v1 (106 items);
- reliability = the separate 30-item three-rater set (not part of the gold) + rater_1's P2-004 blind retest
  (supplementary);
- the comparator row and its pre-registered comparisons come from `phase4`.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

import docnum as D  # noqa: E402
from src.eval.ci_format import fmt_ci  # noqa: E402

OUT = ROOT / "paper/aisigh/tables"
T, P = "R2:tables", "R2:phase4"
SYS = [("majority", "Majority (in-sample)"), ("p2002_candidates", "P2-002 candidates"), ("class_blind", "Class-blind LLM"),
       ("class_aware", "Class-aware LLM"), ("final_agentic", "Final agentic"), ("ablation_a", "Class-blind + verifier"),
       ("long_context", "Long-context (100K)")]


def tex(s: str) -> str:
    return s.replace("−", "$-$").replace("%", "\\%").replace("_", "\\_").replace("κ", "$\\kappa$").replace("ρ", "$\\rho$")


def table(label, caption, cols, header, rows, note="", wide=False) -> str:
    env = "table*" if wide else "table"
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    return (f"% GENERATED by scripts/build_paper_tables_final.py from reports/results_v2.json. Do not edit numbers by hand.\n"
            f"\\begin{{{env}}}[t]\n\\centering\n\\caption{{{caption}}}\n\\label{{{label}}}\n\\footnotesize\n\\setlength{{\\tabcolsep}}{{3pt}}\n"
            f"\\begin{{adjustbox}}{{max width=\\{'textwidth' if wide else 'columnwidth'}}}\n"
            f"\\begin{{tabular}}{{{cols}}}\n\\toprule\n{' & '.join(header)} \\\\\n\\midrule\n{body}\n\\bottomrule\n\\end{{tabular}}\n"
            f"\\end{{adjustbox}}\n"
            + (f"\\par\\smallskip{{\\scriptsize {note}}}\n" if note else "") + f"\\end{{{env}}}\n")


def k3(ref: str) -> str:
    v = D.get(ref)
    lo, hi = v["bootstrap"]["ci95"]
    return f"{v['kappa']:.3f} [{lo:.3f}, {hi:.3f}] ({v['n_items']})"


def a11_cov() -> str:
    v = D.get(P + ".t1_paired.Ablation C on T1: final agentic − class-aware.coverage.diff")
    return tex(f"{v:+.3f}".replace("-", "−"))


def t_benchmark() -> str:
    rows = [["Corpus", f"{D.n(T + '.01_corpus.directions')} Directions; {D.n(T + '.01_corpus.paragraphs')} paragraphs; "
                       f"{D.n(T + '.01_corpus.core_entity_classes')} regulated classes"],
            ["T1 (RQ1, RQ2)", f"{D.n(T + '.05_t1_benchmark.validated')} validated of {D.n(T + '.05_t1_benchmark.sample')} sampled; "
                              f"{sum(D.get(T + '.05_t1_benchmark.judgement_distribution.' + j) for j in ('same', 'different', 'none'))} class units"],
            ["T2 (RQ1)", f"{D.n(T + '.06_t2_retrieval.p3001.t2_xclass_t1.n_scored')} / {D.n(T + '.06_t2_retrieval.p3001.t2_xclass_p2002.n_scored')} / "
                         f"{D.n(T + '.06_t2_retrieval.p3001.t2_supp_p2003.n_scored')} queries (three relevance sets)"],
            ["T3", f"{D.n(T + '.08_t3.scored')} items (of {D.n(T + '.08_t3.built')} built)"],
            ["T4 (RQ3)", f"{D.n(T + '.09_t4.n_questions')} questions $\\times$ 4 answer types"]]
    return table("tab:benchmark", "RBI-ObliBench at a glance.", "ll", ["Component", "Size"], rows)


def t_reliability() -> str:
    irr = T + ".05_t1_benchmark.irr.fleiss"
    rt = T + ".05_t1_benchmark.retest.phase2.all_25"
    rows = [["Separate 30-item set, 3 raters (Fleiss)", k3(irr + ".per_class_judgement"), k3(irr + ".differential_flag"), k3(irr + ".not_obligation")],
            [f"rater\\_1 blind retest ({D.gap().replace('–', '--')}; Cohen)", k3(rt + ".per_class_judgement"), k3(rt + ".differential_flag"),
             k3(rt + ".not_obligation")]]
    return table("tab:reliability", "Reliability evidence: $\\kappa$ [95\\% bootstrap CI] (items). Neither row is computed on the gold items.",
                 "lccc", ["Evidence", "Class judgement", "Flag", "Not-obligation"], rows,
                 note="The 30-item set was drawn outside the T1 sample; the gold is single-expert. The retest is supplementary: recall may inflate agreement.",
                 wide=True)


def t_t1() -> str:
    rows = []
    for k, lab in SYS:
        b = f"{P}.t1_systems.{k}"
        rows.append([lab, D.n(b + ".n_items"), D.ci(b + ".flag_macro_f1"), D.ci(b + ".collapsed_macro_f1"),
                     D.ci(b + ".judgement_macro_f1"), D.f3(f"{P}.t1_different.{k}.different_f1"), D.ci(b + ".coverage")])
    if D.opt(f"{P}.comparator.metrics.n_items", 0):
        b = f"{P}.comparator.metrics"
        rows.append(["Structured comparator", D.n(b + ".n_items"), D.ci(b + ".flag_macro_f1") + "$^*$", D.ci(b + ".collapsed_macro_f1") + "$^*$",
                     D.ci(b + ".judgement_macro_f1"), D.f3(f"{P}.comparator.different.different_f1"), D.ci(b + ".coverage")])
    return table("tab:t1", "T1 on the 106-item gold: 3-way flag Macro-F1, collapsed (absent vs present) Macro-F1, judgement Macro-F1, "
                 "\\textit{different} F1 (point estimate) and coverage.", "lcccccc",
                 ["System", "$n$", "3-way F1", "Collapsed F1", "Judgement F1", "\\textit{diff.} F1", "Coverage"], rows,
                 note="2,000 item resamples. Collapsed F1 is the fair comparison with P2-002, which cannot express shared vs class-specific. "
                      "$^*$Comparator flag derived from its judgements (v3.6 rule); its judgement metrics are the pre-registered ones. "
                      "CIs not computed for the \\textit{diff.} F1 column. Majority (in-sample) uses the gold distribution: a reference, "
                      "not a deployable system. Abstentions are scored as errors, so the verifier's loss in F1 reflects both wrong answers "
                      f"and declined correct ones (coverage {a11_cov()}). Long-context items that exceeded the input cap are excluded rather "
                      f"than penalised, and every comparison with long-context is made on the same {D.n(P + '.t1_systems.long_context.n_items')} items.",
                 wide=True)


def t_t2() -> str:
    sets = ("t2_xclass_t1", "t2_xclass_p2002", "t2_supp_p2003")
    rows = []
    for k, lab in (("bm25", "BM25"), ("dense", "Dense (bge)"), ("hybrid_rrf", "Hybrid RRF"),
                   ("hybrid_minus_source_class", "Hybrid $-$ source class"), ("class_aware", "Class-aware hybrid")):
        rows.append([lab] + [D.ci(T + f".06_t2_retrieval.p3001.{s}.systems.{k}.ndcg") for s in sets])
    n = [D.n(T + f".06_t2_retrieval.p3001.{s}.n_scored") for s in sets]
    return table("tab:t2", "T2 counterpart retrieval, nDCG@10 [95\\% CI].", "lccc",
                 ["System", f"xclass\\_t1 ({n[0]})", f"xclass\\_p2002 ({n[1]})", f"supp\\_p2003 ({n[2]})"], rows,
                 note="The first two sets favour the dense retriever, the third BM25; the class-aware gain is partly by construction.", wide=True)


def t_t3_t4_ablation() -> str:
    abl = D.get(T + ".10_ablations.rows")
    pick = lambda m: next(r["on_minus_off"].split(" (")[0] for r in abl if r["measure"] == m)
    rows = [["T3", "status exact match, filter on (circular)", D.ci(T + ".08_t3.t3.on.status_exact_match")],
            ["T3", "status exact match, filter off", D.ci(T + ".08_t3.t3.off.status_exact_match")],
            ["T4", "concatenated $-$ genuine (RePASs)", D.ci(T + ".09_t4.paired.concatenated - genuine.composite_score").split(" (")[0]],
            ["T4", "negated $-$ genuine", D.ci(T + ".09_t4.paired.adv_negated - genuine.composite_score").split(" (")[0]],
            ["T4", "off-topic $-$ genuine", D.ci(T + ".09_t4.paired.adv_offtopic - genuine.composite_score").split(" (")[0]],
            ["T4", "$\\rho$(RePASs, human faithful)", D.ci(T + ".09_t4.human.all_rated.spearman_composite_score_vs_faithful")],
            ["T4", "$\\rho$(RePASs, answers question)", D.ci(T + ".09_t4.human.all_rated.spearman_composite_score_vs_answers_question")],
            ["A", "class filter: T2 nDCG@10 (xclass\\_t1)", pick("T2 nDCG@10, t2_xclass_t1")],
            ["A", "class filter (with verifier): T1 3-way F1", pick("T1 3-way flag Macro-F1")],
            ["B", "temporal filter: T3 exact match", pick("T3 status exact match")],
            ["C", "verifier: T1 3-way F1", D.ci(P + ".t1_paired.Ablation C on T1: final agentic − class-aware.flag_macro_f1").split(" (")[0]],
            ["C", "verifier: T4 abstention", pick("T4 abstention rate")]]
    return table("tab:t3t4", "T3, T4 and ablations A--C (ON $-$ OFF), 95\\% CI.", "llc", ["", "Measure", "Value"], rows,
                 note="T3 gold and filter share one parser. T4 verdicts are pre-registered; unchanged without the 2 bad questions.")


def t_comparator() -> str:
    if not D.opt(f"{P}.comparator.metrics.n_items", 0):
        return "% comparator T1 run not complete: table omitted\n"
    rows = []
    # One row per measure, one column per comparison, so the table fits a single column.
    for m, lab in (("judgement_macro_f1", "$\\Delta$ judgement F1"), ("different_f1", "$\\Delta$ \\textit{diff.} F1"),
                   ("different_recall", "$\\Delta$ \\textit{diff.} recall")):
        rows.append([lab] + [D.ci(f"{P}.preregistered_comparisons.comparator − {b}.judgement.{m}").split(" (")[0]
                             for b in ("class_aware", "p2002_candidates")])
    m = f"{P}.missed_by_every_llm_system"
    note = (f"Gold \\textit{{different}} units missed by every LLM system: {D.n(m + '.A_all_five_answered.missed')}/{D.n(m + '.gold_different_units')} "
            f"when all five answered; {D.n(m + '.B_answered_only.missed')} counting answered systems only. The comparator gets "
            f"{D.n(m + '.A_all_five_answered.comparator_correct')} and {D.n(m + '.B_answered_only.comparator_correct')} of them right.")
    return table("tab:cmp", "Pre-registered comparator comparisons on the gold (paired item bootstrap, 95\\% CI).", "lcc",
                 ["Comparator minus", "Class-aware LLM", "P2-002"], rows, note=note)


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, fn in [("tab_benchmark", t_benchmark), ("tab_reliability", t_reliability), ("tab_t1_systems", t_t1), ("tab_t2", t_t2),
                     ("tab_t3_t4_ablation", t_t3_t4_ablation), ("tab_comparator", t_comparator)]:
        (OUT / f"{name}.tex").write_text(fn(), encoding="utf-8")
    (OUT / "sources_final.json").write_text(json.dumps(D.used_report(), indent=1) + "\n")
    print("tables written:", sorted(p.name for p in OUT.glob("*.tex")))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
